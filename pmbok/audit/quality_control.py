"""
Quality Control Module

Provides audit and inspection mechanisms to ensure LLM-generated outputs are relevant
to the provided context and do not hallucinate unrelated content.
"""

import json
import re
from typing import Dict, List, Any, Tuple
from difflib import SequenceMatcher

from pmbok.models.pmbok import ProjectArtifact


class QualityControlResult:
    """Result of quality control audit."""

    def __init__(
        self,
        is_passing: bool,
        score: float,
        issues: List[str],
        audit_details: Dict[str, Any]
    ):
        self.is_passing = is_passing
        self.score = score  # 0.0 to 1.0
        self.issues = issues
        self.audit_details = audit_details

    def to_dict(self) -> Dict[str, Any]:
        return {
            "is_passing": self.is_passing,
            "score": self.score,
            "issues": self.issues,
            "audit_details": self.audit_details
        }


class ContentQualityController:
    """
    Audits LLM-generated content for relevance and hallucination prevention.
    """

    def __init__(self, min_relevance_score: float = 0.6):
        self.min_relevance_score = min_relevance_score

    def audit_output_quality(
        self,
        input_artifacts: List[ProjectArtifact],
        output_artifacts: List[ProjectArtifact],
        project_context: Dict[str, Any]
    ) -> QualityControlResult:
        """
        Audit the quality of generated output artifacts.

        Args:
            input_artifacts: Artifacts that were provided as input to the process
            output_artifacts: Artifacts generated by the LLM
            project_context: Overall project context (ideation, business case, charter)

        Returns:
            QualityControlResult with audit findings
        """
        issues = []
        audit_details = {
            "input_analysis": {},
            "output_analysis": {},
            "relevance_checks": [],
            "hallucination_checks": []
        }

        # Extract key terms from inputs and project context
        input_terms = self._extract_key_terms(input_artifacts + [self._context_to_artifact(project_context)])
        audit_details["input_analysis"]["key_terms"] = input_terms

        # Analyze each output artifact
        total_score = 0.0
        artifact_scores = []

        for output_artifact in output_artifacts:
            artifact_score, artifact_issues, artifact_details = self._audit_single_artifact(
                output_artifact, input_terms, project_context
            )
            artifact_scores.append(artifact_score)
            issues.extend(artifact_issues)
            audit_details["output_analysis"][output_artifact.artifact_type] = artifact_details
            total_score += artifact_score

        # Calculate overall score
        if artifact_scores:
            overall_score = total_score / len(artifact_scores)
        else:
            overall_score = 0.0

        # Determine if passing
        is_passing = overall_score >= self.min_relevance_score and len(issues) == 0

        audit_details["overall_score"] = overall_score
        audit_details["artifact_scores"] = artifact_scores

        return QualityControlResult(
            is_passing=is_passing,
            score=overall_score,
            issues=issues,
            audit_details=audit_details
        )

    def _audit_single_artifact(
        self,
        artifact: ProjectArtifact,
        input_terms: List[str],
        project_context: Dict[str, Any]
    ) -> Tuple[float, List[str], Dict[str, Any]]:
        """Audit a single output artifact."""
        issues = []
        details = {}
        scores = []

        # Extract content as text
        content_text = self._extract_content_text(artifact.content)
        details["content_length"] = len(content_text)
        details["content_preview"] = content_text[:200] + "..." if len(content_text) > 200 else content_text

        # Check for hallucination - compare against project context
        project_title = project_context.get("title", "").lower()
        content_lower = content_text.lower()

        # Check if content mentions the correct project
        # SequenceMatcher.ratio() can be very low for long documents.
        # We supplement it with word overlap analysis.
        title_words = {w for w in re.findall(r'\b\w+\b', project_title) if len(w) > 3}
        content_words = {w for w in re.findall(r'\b\w+\b', content_lower) if len(w) > 3}
        
        if title_words:
            word_overlap = len(title_words.intersection(content_words)) / len(title_words)
        else:
            word_overlap = 0.0

        # Refined similarity combining SequenceMatcher and word overlap
        title_similarity = max(word_overlap, self._calculate_similarity(project_title, content_lower))

        # EXEMPTION for naturally empty artifacts like Change Requests or Updates
        # Or major plans that might paraphrase correctly but trigger low strict similarity
        is_side_effect_artifact = any(kw in artifact.artifact_type.lower() for kw in ["change request", "update", "log", "register", "updates"])
        is_major_plan = any(kw in artifact.artifact_type.lower() for kw in ["plan", "charter", "register"])
        
        is_logically_empty = len(content_text.strip()) < 100 and ("[]" in content_text or "{}" in content_text)
        
        # Heuristic: If we match at least 2 major keywords (>4 chars) of the title, we consider it a match
        major_title_words = [w for w in title_words if len(w) > 4]
        matches = len([w for w in major_title_words if w in content_lower])
        
        if (is_side_effect_artifact and is_logically_empty) or (matches >= 2):
            title_similarity = 1.0 # Grant pass
            word_overlap = 1.0     # Grant pass

        if title_similarity < 0.1: # Lowered threshold from 0.2 to 0.1
            issues.append(f"Content does not reference the correct project title (similarity score: {title_similarity:.2f})")
            scores.append(0.0)
        else:
            scores.append(title_similarity)

        # Check for key term relevance
        relevant_terms_found = 0
        for term in input_terms[:10]:  # Check top 10 terms
            if term.lower() in content_lower:
                relevant_terms_found += 1

        term_relevance_score = relevant_terms_found / max(len(input_terms[:10]), 1)
        if term_relevance_score < 0.05: # Lowered from 0.2 to 0.05 (requires only 1 match if 10+ terms)
            issues.append(f"Low relevance to input terms (found {relevant_terms_found}/{min(10, len(input_terms))} key terms)")
        scores.append(term_relevance_score)

        # Check for generic/unrelated content patterns
        # Filter these indicators so we don't flag the ACTUAL project topic
        project_text = str(project_context).lower()
        hallucination_indicators = [
            "enterprise resource planning",
            "erp implementation",
            "supply chain management",
            "financial system",
            "hr system"
        ]
        active_indicators = [ind for ind in hallucination_indicators if ind not in project_text]

        found_indicators = [ind for ind in active_indicators if ind in content_lower]
        if found_indicators:
            issues.append(f"Potential hallucination or generic content detected: {found_indicators}")
            scores.append(0.0)
        else:
            scores.append(1.0)

        # Calculate final score for this artifact
        if scores:
            final_score = sum(scores) / len(scores)
        else:
            final_score = 0.0

        details["scores"] = {
            "title_similarity": scores[0] if len(scores) > 0 else 0,
            "term_relevance": scores[1] if len(scores) > 1 else 0,
            "hallucination_check": scores[2] if len(scores) > 2 else 0,
            "final_score": final_score
        }

        return final_score, issues, details

    def _extract_key_terms(self, artifacts: List[ProjectArtifact]) -> List[str]:
        """Extract key terms from input artifacts."""
        all_text = ""
        for artifact in artifacts:
            all_text += self._extract_content_text(artifact.content) + " "

        # Simple term extraction - split by whitespace and filter
        words = re.findall(r'\b\w+\b', all_text.lower())
        # Remove common stop words and short words
        stop_words = {'the', 'a', 'an', 'and', 'or', 'but', 'in', 'on', 'at', 'to', 'for', 'of', 'with', 'by', 'is', 'are', 'was', 'were', 'be', 'been', 'being', 'have', 'has', 'had', 'do', 'does', 'did', 'will', 'would', 'could', 'should', 'may', 'might', 'must', 'can', 'shall'}
        terms = [word for word in words if len(word) > 3 and word not in stop_words]

        # Get most frequent terms
        from collections import Counter
        term_counts = Counter(terms)
        return [term for term, count in term_counts.most_common(20)]

    def _extract_content_text(self, content: Any) -> str:
        """Extract readable text from artifact content."""
        if isinstance(content, str):
            return content
        elif isinstance(content, dict):
            # Flatten dict to text
            return json.dumps(content, sort_keys=True)
        elif isinstance(content, list):
            return " ".join(str(item) for item in content)
        else:
            return str(content)

    def _calculate_similarity(self, text1: str, text2: str) -> float:
        """Calculate text similarity score."""
        return SequenceMatcher(None, text1, text2).ratio()

    def _context_to_artifact(self, context: Dict[str, Any]) -> ProjectArtifact:
        """Convert project context to a pseudo-artifact for term extraction."""
        return ProjectArtifact(
            run_id="context",
            process_id="context",
            artifact_type="ProjectContext",
            version=1,
            content=context,
            produced_by="context"
        )


# Global quality controller instance
quality_controller = ContentQualityController()